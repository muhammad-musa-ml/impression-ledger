// Writes results/fault-drill/SUMMARY.md from the run-*.json files next to it.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(process.argv[2] ?? path.join(HERE, '..', '..', 'results', 'fault-drill'));

interface Probe {
  window: string;
  pass: boolean;
  eventsSent: number;
  eventsStoredAfterKill: number;
  acceptedOnResend: number;
}

interface Run {
  run: number;
  seed: number;
  pass: boolean;
  code: { commit: string; dirty: boolean };
  machine: { platform: string; release: string; arch: string; logicalCpus: number; node: string; postgres: string };
  settings: { viewsPerTenant: number; batchSize: number; concurrency: number; holdBeforeCommitMs: number; holdAfterCommitMs: number };
  delivery: { distinctEvents: number; deliveries: number; duplicateDeliveries: number; batches: number; replayedBatches: number };
  faults: {
    kills: number;
    killsBeforeCommit: number;
    killsBeforeCommitWithOpenTransaction: number;
    killsAfterCommit: number;
    killsAfterCommitWithCommitLogged: number;
    failedAttempts: number;
    unexpectedServerExits: number;
    probes: Probe[];
  };
  server: { acceptedInAckedResponses: number; committedUnderLostReply: number; deadlockRetries: number };
  result: {
    eventsExpected: number;
    eventsStored: number;
    gaps: number;
    extra: number;
    semanticDuplicates: number;
    viewVerdictMismatches: number;
    reportMismatches: number;
    derivedStateMismatches: number;
  };
}

const files = (await readdir(dir)).filter((f) => /^run-\d+\.json$/.test(f)).sort();
const runs: Run[] = [];
for (const f of files) runs.push(JSON.parse(await readFile(path.join(dir, f), 'utf8')) as Run);
if (runs.length === 0) throw new Error(`no run-*.json files in ${dir}`);

const first = runs[0]!;
const probeCell = (r: Run, window: string): string => {
  const p = r.faults.probes.find((x) => x.window === window)!;
  return `${p.eventsStoredAfterKill} of ${p.eventsSent}`;
};
const rows = runs.map((r) => {
  const mismatches = r.result.viewVerdictMismatches + r.result.reportMismatches + r.result.derivedStateMismatches;
  return (
    `| ${r.run} | ${r.seed} | ${r.delivery.distinctEvents} | ${r.delivery.deliveries} | ` +
    `${r.faults.killsBeforeCommit} (${r.faults.killsBeforeCommitWithOpenTransaction}) | ` +
    `${r.faults.killsAfterCommit} (${r.faults.killsAfterCommitWithCommitLogged}) | ${r.faults.failedAttempts} | ` +
    `${r.server.committedUnderLostReply} | ${r.result.eventsStored} | ${r.result.gaps} | ${r.result.extra} | ` +
    `${r.result.semanticDuplicates} | ${mismatches} | ` +
    `${probeCell(r, 'before-commit')} / ${probeCell(r, 'after-commit')} | ${r.pass ? 'pass' : 'FAIL'} |`
  );
});

const commits = [...new Set(runs.map((r) => r.code.commit))];
const text = `# Fault drill results

Generated by \`npm run drill:summary\` from the \`run-*.json\` files in this folder. Do not edit by hand.

${runs.length} runs, seeds ${runs.map((r) => r.seed).join(', ')}. Code commit${commits.length > 1 ? 's' : ''}: ${commits.map((c) => c.slice(0, 12)).join(', ')}${runs.some((r) => r.code.dirty) ? ' (working tree had uncommitted changes in src, scripts, migrations or package.json)' : ''}.
Machine: ${first.machine.platform} ${first.machine.release} ${first.machine.arch}, ${first.machine.logicalCpus} logical CPUs, Node ${first.machine.node}, PostgreSQL ${first.machine.postgres}.
Each run: 2 tenants x ${first.settings.viewsPerTenant} views, batches of ${first.settings.batchSize}, ${first.settings.concurrency} requests in flight, a transaction held ${first.settings.holdBeforeCommitMs} ms before COMMIT and the reply held ${first.settings.holdAfterCommitMs} ms after it.

| run | seed | distinct events | deliveries | kills before COMMIT (open txn in log) | kills after COMMIT (commit in log) | failed attempts | committed under a lost reply | events stored | gaps | extra | duplicate rows | verdict mismatches | probe rows stored after kill (before / after COMMIT) | result |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

Columns: *deliveries* counts every event sent, repeats included. *kills* are SIGKILLs of the server process during the replay, followed by a restart; the number in brackets is how many of them had the evidence named in the header in the server's own log when the kill was sent. *failed attempts* are requests that got no usable answer because the server was down or killed. *committed under a lost reply* is the number of distinct events whose first successful write was in a request the client never saw answered. *gaps* are sent events missing from the database, *extra* are stored events nobody sent, *duplicate rows* are events stored twice under different ids. *verdict mismatches* add up the per-view, per-ad report and recomputed-from-events differences. *probe rows stored after kill* is how many rows of a single probe batch were in the database right after the server was killed in that window (0 of N is the expected answer before COMMIT, N of N after it).
`;
await writeFile(path.join(dir, 'SUMMARY.md'), text, 'utf8');
console.log(`wrote ${path.join(dir, 'SUMMARY.md')} from ${runs.length} runs`);
